// Generate all raster/container variants from the repository-owned vector.
// Usage: node scripts/build-eduwork-icons.mjs --sharp <sharp module path>
import { readFile, writeFile } from 'node:fs/promises'
import { resolve, dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { parseArgs } from 'node:util'
const { values } = parseArgs({ options: { sharp: { type: 'string' } } })
const sharp = (await import(values.sharp ? pathToFileURL(resolve(values.sharp)).href : 'sharp')).default
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const output = join(root, 'assets/eduwork')
const master = await readFile(join(output, 'mark.svg'), 'utf8')
const shape = /d="([^"]+)"/.exec(master)[1]
const DEFAULT_ICON_COLOR = '#9f2636'
const icon = color => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><title>EduWork</title><rect width="256" height="256" rx="56" fill="${color}"/><path fill="#fff" transform="translate(43 32) scale(.665 .78)" d="${shape}"/></svg>`
for (const [name, color] of [['icon', DEFAULT_ICON_COLOR], ['icon-red', DEFAULT_ICON_COLOR], ['icon-blue', '#2575ff']]) await writeFile(join(output, name + '.svg'), icon(color))
await writeFile(join(output,'mark-mono.svg'), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><path fill="currentColor" d="${shape}"/></svg>`)
const sizes = [16, 20, 24, 32, 48, 64, 128, 256, 512, 1024]
const pngs = new Map()
for (const size of sizes) {
  const bytes = await sharp(Buffer.from(icon(DEFAULT_ICON_COLOR))).resize(size,size).png().toBuffer()
  pngs.set(size, bytes)
  await writeFile(join(output, `icon-${size}.png`), bytes)
}
for (const color of ['black', 'white']) await writeFile(join(output, `tray-${color}.png`), await sharp(Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><path fill="${color}" d="${shape}"/></svg>`)).resize(32,32).png().toBuffer())
const icoSizes = sizes.filter(size => size <= 256), head = Buffer.alloc(6 + 16 * icoSizes.length)
head.writeUInt16LE(1,2);head.writeUInt16LE(icoSizes.length,4)
let offset=head.length
for(let i=0;i<icoSizes.length;i++) {
  const size=icoSizes[i], png=pngs.get(size), at=6+16*i
  head[at]=head[at+1]=size===256?0:size;head.writeUInt16LE(1,at+4);head.writeUInt16LE(32,at+6)
  head.writeUInt32LE(png.length,at+8);head.writeUInt32LE(offset,at+12);offset+=png.length
}
await writeFile(join(output,'icon.ico'),Buffer.concat([head,...icoSizes.map(size=>pngs.get(size))]))
const chunks=[]
for(const [type,size] of [['icp4',16],['icp5',32],['icp6',64],['ic07',128],['ic08',256],['ic09',512],['ic10',1024]]) {
  const png=pngs.get(size), header=Buffer.alloc(8);header.write(type);header.writeUInt32BE(png.length+8,4);chunks.push(header,png)
}
const icns=Buffer.alloc(8);icns.write('icns');icns.writeUInt32BE(8+chunks.reduce((sum,x)=>sum+x.length,0),4)
await writeFile(join(output,'icon.icns'),Buffer.concat([icns,...chunks]))
// Generated client constant lets UI theme color change without another logo geometry.
await writeFile(join(root,'dsh-plugins/client-ui-branding/src/eduwork-mark.js'), `// Generated by scripts/build-eduwork-icons.mjs from assets/eduwork/mark.svg.\nexport const eduworkMarkPath = ${JSON.stringify(shape)}\n`)
console.log('EduWork vector, PNG, ICO, ICNS and theme geometry generated.')
