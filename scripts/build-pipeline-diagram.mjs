const scriptRoot = dirname(fileURLToPath(import.meta.url))
const coreRoot = join(scriptRoot, '..')

const xml = value => String(value)
  .replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')
  .replaceAll('"', '&quot;')

const STAGE_LABELS = {
  web: { name: '构建 Web 产品', summary: '审计源码并装配 Web' },
  'host-adapter': { name: '构建桌面 Host', summary: '生成桌面通信适配器' },
  product: { name: '生成桌面产品', summary: '汇集 Web 与 Host' },
  electron: { name: '准备 Electron', summary: '获取锁定的运行时' },
  shell: { name: '构建桌面外壳', summary: '编译 Electron 界面' },
  'install-host': { name: '安装 Host', summary: '将适配器写入产品' },
  'native-inputs': { name: '准备原生资源', summary: '获取对应系统的资源' },
  'native-install': { name: '安装原生资源', summary: '将资源写入产品' },
  sparkle: { name: '准备 Mac 更新', summary: '配置 Sparkle 更新组件' },
  desktop: { name: '打包桌面应用', summary: '生成目标系统的安装包' },
  accept: { name: '验收桌面包', summary: '检查打包后的启动' },
  publish: { name: '生成交付文件', summary: '整理归档与构建回执' },
}

function stageLabel(name) {
  const label = STAGE_LABELS[name]
  if (!label) throw new Error(`A diagram label is missing for stage ${name}`)
  return label
}

// ---------------------------------------------------------------- drawio ----

/** Geometry: keep the independent inputs apart and collect package prerequisites. */
const COLUMN_WIDTH = 260
const ROW_HEIGHT = 130
const BOX_WIDTH = 200
const BOX_HEIGHT = 60
const MARGIN = 64

const DIAGRAM_POSITIONS = {
  web: [0, 0],
  'native-inputs': [2, 4],
  'host-adapter': [1, 1],
  electron: [3, 0],
  product: [2, 2],
  shell: [3, 1],
  'install-host': [3, 2],
  'native-install': [3, 3],
  sparkle: [3, 4],
  desktop: [5, 2],
  accept: [6, 2],
  publish: [7, 2],
}

function layout(stages) {
  const placed = new Map()
  for (const entry of stages) {
    const position = DIAGRAM_POSITIONS[entry.name]
    if (!position) throw new Error(`A diagram position is missing for stage ${entry.name}`)
    placed.set(entry.name, {
      x: MARGIN + position[0] * COLUMN_WIDTH,
      y: MARGIN + position[1] * ROW_HEIGHT,
    })
  }
  return { placed, width: MARGIN * 2 + 8 * COLUMN_WIDTH, height: MARGIN * 2 + 5 * ROW_HEIGHT }
}

function drawioXml({ title, stages, edges }) {
  const { placed, width, height } = layout(stages)
  const cells = []
  let id = 0
  const nextId = () => `n${id += 1}`

  const ids = new Map()
  for (const entry of stages) {
    const spot = placed.get(entry.name)
    const cellId = nextId()
    ids.set(entry.name, cellId)
    const labelText = stageLabel(entry.name)
    const label = [
      labelText.name,
      labelText.summary,
      `${entry.name}${entry.platforms === 'macos' ? ' · 仅 macOS' : ''}`,
    ].join('\n')
    cells.push(`        <mxCell id="${cellId}" value="${xml(label)}" style="rounded=1;whiteSpace=wrap;html=1;fillColor=${entry.platforms === 'macos' ? '#ddf4ff' : '#ffffff'};strokeColor=${entry.platforms === 'macos' ? '#0969da' : '#d0d7de'};fontSize=11;" vertex="1" parent="1">
          <mxGeometry x="${spot.x}" y="${spot.y}" width="${BOX_WIDTH}" height="${BOX_HEIGHT}" as="geometry"/>
        </mxCell>`)
  }

  const joinId = nextId()
  const desktop = placed.get('desktop')
  cells.push(`        <mxCell id="${joinId}" value="" style="ellipse;fillColor=none;strokeColor=none;opacity=0;" vertex="1" parent="1">
          <mxGeometry x="${desktop.x - 56}" y="${desktop.y + BOX_HEIGHT / 2}" width="1" height="1" as="geometry"/>
        </mxCell>`)
  const edgeCells = edges.map(({ from, to, macOnly }) => {
    const packageInput = to === 'desktop'
    const vertical = from === 'native-install' && to === 'sparkle'
    const exit = vertical ? 'exitX=0.5;exitY=1;' : 'exitX=1;exitY=0.5;'
    const entry = vertical ? 'entryX=0.5;entryY=0;' : packageInput
      ? 'entryX=0.5;entryY=0.5;' : 'entryX=0;entryY=0.5;'
    return `        <mxCell id="${nextId()}" style="edgeStyle=none;curved=1;html=1;strokeColor=${macOnly ? '#0969da' : '#1f883d'};strokeWidth=1.6;endArrow=${packageInput ? 'none' : 'block'};${exit}${entry}" edge="1" parent="1" source="${ids.get(from)}" target="${packageInput ? joinId : ids.get(to)}">
          <mxGeometry relative="1" as="geometry"/>
        </mxCell>`
  })
  edgeCells.push(`        <mxCell id="${nextId()}" style="edgeStyle=none;curved=1;html=1;strokeColor=#1f883d;strokeWidth=1.8;endArrow=block;exitX=1;exitY=0.5;entryX=0;entryY=0.5;" edge="1" parent="1" source="${joinId}" target="${ids.get('desktop')}">
          <mxGeometry relative="1" as="geometry"/>
        </mxCell>`)

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/build-pipeline-diagram.mjs — do not edit by hand. -->
<mxfile host="EduWork" version="24.0.0">
  <diagram id="build-pipeline" name="${xml(title)}">
    <mxGraphModel dx="1200" dy="800" grid="1" gridSize="10" guides="1" tooltips="1" connect="1" arrows="1" fold="1" page="1" pageScale="1" pageWidth="${width + MARGIN * 2}" pageHeight="${height + MARGIN * 2}" math="0" shadow="0">
      <root>
        <mxCell id="0"/>
        <mxCell id="1" parent="0"/>
${cells.join('\n')}
${edgeCells.join('\n')}
      </root>
    </mxGraphModel>
  </diagram>
</mxfile>
`
}

// ------------------------------------------------------------------- svg ----

const CARD_W = 210
const CARD_H = 104
const COL_GAP = 92
const PAD_X = 48
const PAD_TOP = 160
const ROW_STEP = 130
const PAD_BOTTOM = 80

// GitHub's own palette, so the diagram reads as part of the product's docs
// rather than as a separate drawing.
const C = {
  bg: '#ffffff',
  border: '#d0d7de',
  ink: '#1f2328',
  muted: '#59636e',
  faint: '#8c959f',
  card: '#ffffff',
  cardEdge: '#d0d7de',
  macCard: '#ddf4ff',
  macEdge: '#0969da',
  solid: '#1f883d',
}

function svgDiagram({ title, subtitle, stages, edges }) {
  const width = PAD_X * 2 + 8 * CARD_W + 7 * COL_GAP
  const height = PAD_TOP + 4 * ROW_STEP + CARD_H + PAD_BOTTOM
  const pos = name => {
    const position = DIAGRAM_POSITIONS[name]
    if (!position) throw new Error(`A diagram position is missing for stage ${name}`)
    return { x: PAD_X + position[0] * (CARD_W + COL_GAP), y: PAD_TOP + position[1] * ROW_STEP }
  }
  const font = '-apple-system,BlinkMacSystemFont,"PingFang SC","Microsoft YaHei","Noto Sans CJK SC","Segoe UI",sans-serif'
  const mono = 'ui-monospace,SFMono-Regular,Menlo,monospace'

  const parts = []
  parts.push(`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-label="${xml(title)}">`)
  parts.push(`<style>
  .t{font:600 16px ${font};fill:${C.ink}}
  .s{font:400 12px ${font};fill:${C.muted}}
  .h{font:600 17px ${font};fill:${C.ink}}
  .p{font:400 11px ${mono};fill:${C.faint}}
</style>`)
  parts.push(`<rect width="${width}" height="${height}" fill="${C.bg}"/>`)
  // Header strip: the pipeline identity and a summary line, the way a workflow
  // run page presents a run.
  parts.push(`<rect x="${PAD_X - 17}" y="18" width="${width - (PAD_X - 17) * 2}" height="58" rx="8" fill="${C.bg}" stroke="${C.border}"/>`)
  parts.push(`<circle cx="${PAD_X - 1}" cy="41" r="5" fill="${C.solid}"/>`)
  parts.push(`<text class="h" x="${PAD_X + 14}" y="46">${xml(title)}</text>`)
  parts.push(`<text class="s" x="${PAD_X - 1}" y="65">${xml(subtitle)}</text>`)

  // The package prerequisites occupy one vertical column. Their curves share
  // a short final segment, leaving only one arrow at the package card.
  const packageInputs = []
  for (const edge of edges) {
    const from = pos(edge.from)
    const to = pos(edge.to)
    const x1 = from.x + CARD_W, y1 = from.y + CARD_H / 2
    const x2 = to.x, y2 = to.y + CARD_H / 2
    if (edge.to === 'desktop') {
      packageInputs.push({ from: edge.from, x1, y1, macOnly: edge.macOnly })
      continue
    }
    let path
    if (edge.from === 'native-install' && edge.to === 'sparkle') {
      const center = from.x + CARD_W / 2
      path = `M${center} ${from.y + CARD_H} C${center} ${from.y + CARD_H + 10} ${center} ${to.y - 10} ${center} ${to.y}`
    } else {
      const bend = Math.min(75, (x2 - x1) * 0.45)
      path = `M${x1} ${y1} C${x1 + bend} ${y1} ${x2 - bend} ${y2} ${x2} ${y2}`
    }
    parts.push(`<path d="${path}" fill="none" stroke="${edge.macOnly ? C.macEdge : C.solid}" stroke-width="1.7" stroke-linecap="round" marker-end="url(#${edge.macOnly ? 'ahm' : 'ah'})"/>`)
  }
  const packageOrder = ['electron', 'shell', 'install-host', 'native-install', 'sparkle']
  const target = pos('desktop')
  const joinX = target.x - 72
  const joinY = target.y + CARD_H / 2
  for (const input of packageInputs) {
    if (!packageOrder.includes(input.from)) throw new Error(`Unexpected package input in diagram: ${input.from}`)
    const bend = (joinX - input.x1) * 0.48
    const path = `M${input.x1} ${input.y1} C${input.x1 + bend} ${input.y1} ${joinX - bend} ${joinY} ${joinX} ${joinY}`
    parts.push(`<path d="${path}" fill="none" stroke="${input.macOnly ? 'url(#macJoin)' : C.solid}" stroke-width="1.7" stroke-linecap="round"/>`)
  }
  parts.push(`<path d="M${joinX} ${joinY} H${target.x}" fill="none" stroke="${C.solid}" stroke-width="1.8" marker-end="url(#ah)"/>`)
  const macInput = packageInputs.find(input => input.macOnly)
  if (!macInput) throw new Error('The macOS branch is missing from the diagram')
  parts.push(`<defs>
  <linearGradient id="macJoin" gradientUnits="userSpaceOnUse" x1="${macInput.x1}" y1="0" x2="${joinX}" y2="0"><stop offset="0" stop-color="${C.macEdge}"/><stop offset="1" stop-color="${C.solid}"/></linearGradient>
  <marker id="ah" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto"><path d="M0 0 L10 5 L0 10 z" fill="${C.solid}"/></marker>
  <marker id="ahm" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto"><path d="M0 0 L10 5 L0 10 z" fill="${C.macEdge}"/></marker>
</defs>`)

  for (const entry of stages) {
    const p = pos(entry.name)
    const macOnly = entry.platforms === 'macos'
    const label = stageLabel(entry.name)
    parts.push(`<g data-stage="${xml(entry.name)}"><rect x="${p.x}" y="${p.y}" width="${CARD_W}" height="${CARD_H}" rx="8" fill="${macOnly ? C.macCard : C.card}" stroke="${macOnly ? C.macEdge : C.cardEdge}" stroke-width="1"/>`)
    parts.push(`<text class="t" x="${p.x + 15}" y="${p.y + 30}">${xml(label.name)}</text>`)
    parts.push(`<text class="s" x="${p.x + 15}" y="${p.y + 55}">${xml(label.summary)}</text>`)
    parts.push(`<text class="p" x="${p.x + 15}" y="${p.y + 82}">${xml(entry.name)}</text>`)
    if (macOnly) parts.push(`<text class="s" x="${p.x + CARD_W - 14}" y="${p.y + 82}" text-anchor="end">仅 macOS</text>`)
    parts.push(`</g>`)
  }
  parts.push(`</svg>`)
  return `${parts.join('\n')}\n`
}

// --------------------------------------------------------------- mermaid ----

function mermaidDiagram({ stages, edges }) {
  const lines = [
    '%% Generated by scripts/build-pipeline-diagram.mjs — do not edit by hand.',
    '%%{init: {"flowchart": {"curve": "basis"}}}%%',
    'flowchart LR',
  ]
  const node = entry => {
    const label = stageLabel(entry.name)
    const shape = `["${label.name}<br/>${label.summary}<br/>${entry.name}${entry.platforms === 'macos' ? ' · 仅 macOS' : ''}"]`
    return `  ${entry.name.replaceAll('-', '_')}${shape}`
  }
  for (const entry of stages) lines.push(node(entry))
  lines.push('  join(( ))')
  edges.forEach(({ from, to, macOnly }, index) => {
    lines.push(`  ${from.replaceAll('-', '_')} ${to === 'desktop' ? '--- join' : `--> ${to.replaceAll('-', '_')}`}`)
    if (macOnly) lines.push(`  linkStyle ${index} stroke:${C.macEdge},stroke-width:2px`)
  })
  lines.push('  join --> desktop')
  lines.push('  style join fill:transparent,stroke:transparent,color:transparent')
  lines.push(`  classDef macOnly fill:${C.macCard},stroke:${C.macEdge}`)
  lines.push('  class sparkle macOnly')
  return `${lines.join('\n')}\n`
}

function sharedDiagramStages(platforms) {
  const windows = new Map(platforms.windows.map(entry => [entry.name, entry]))
  const macos = new Map(platforms.macos.map(entry => [entry.name, entry]))
  const macOnly = [...macos.keys()].filter(name => !windows.has(name))
  if (macOnly.length !== 1 || macOnly[0] !== 'sparkle') {
    throw new Error(`Unexpected platform-specific stages: ${macOnly.join(', ')}`)
  }
  for (const entry of platforms.windows) {
    const mac = macos.get(entry.name)
    if (!mac) throw new Error(`Windows-only stage needs a diagram branch: ${entry.name}`)
    for (const kind of ['requires', 'dependsOn', 'outputs', 'mutableOutputs']) {
      const actual = kind === 'requires' || kind === 'dependsOn'
        ? mac[kind].filter(name => name !== 'sparkle') : mac[kind]
      if (JSON.stringify(actual) !== JSON.stringify(entry[kind])) {
        throw new Error(`Platform dependencies differ for ${entry.name}.${kind}`)
      }
    }
  }
  const descriptions = {
    'native-inputs': 'Platform-native resources',
    desktop: 'Electron desktop package',
    publish: 'Archive, receipt and update metadata',
  }
  return platforms.macos.map(entry => ({
    name: entry.name,
    description: descriptions[entry.name] ?? entry.description,
    requires: entry.requires,
    dependsOn: entry.dependsOn,
    outputs: entry.outputs,
    mutableOutputs: entry.mutableOutputs,
    platforms: entry.name === 'sparkle' ? 'macos' : 'both',
  }))
}

// Keep the paths needed to explain ordering on either platform. An edge that
// can already be followed through another stage on both platforms adds clutter.
function diagramEdges(platforms) {
  const visible = new Map()
  for (const [platform, stages] of Object.entries(platforms)) {
    const all = stages.flatMap(entry => [...entry.requires, ...entry.dependsOn]
      .map(from => ({ from, to: entry.name })))
    const reaches = (from, to, omitted) => {
      const pending = [from]
      const visited = new Set()
      while (pending.length) {
        const current = pending.pop()
        if (current === to) return true
        if (visited.has(current)) continue
        visited.add(current)
        for (const edge of all) {
          if (edge !== omitted && edge.from === current) pending.push(edge.to)
        }
      }
      return false
    }
    for (const edge of all) {
      if (reaches(edge.from, edge.to, edge)) continue
      const key = `${edge.from}->${edge.to}`
      if (!visible.has(key)) visible.set(key, { ...edge, platforms: new Set() })
      visible.get(key).platforms.add(platform)
    }
  }
  return [...visible.values()].map(edge => ({
    from: edge.from,
    to: edge.to,
    macOnly: edge.platforms.size === 1 && edge.platforms.has('macos'),
  }))
}

// --------------------------------------------------------------- catalog ----

function catalog({ platform, stages }) {
  const waves = parallelSets(stages)
  return {
    platform,
    generatedFrom: 'stage declarations in scripts/lib/*-stages.mjs',
    stages: stages.length,
    maxParallelism: Math.max(...waves.map(wave => wave.length)),
    waves: waves.map((wave, index) => ({ wave: index, stages: wave })),
    detail: stages.map(entry => ({
      name: entry.name,
      description: entry.description,
      requires: entry.requires,
      dependsOn: entry.dependsOn,
      outputs: entry.outputs,
      mutableOutputs: entry.mutableOutputs,
      clean: entry.clean,
    })),
  }
}

/** A stable digest of the rendered assets, for a caller that wants to pin them. */
export function assetsDigest(assets) {
  return createHash('sha256').update(JSON.stringify(assets)).digest('hex')
}

export async function buildPipelineDiagrams({ output }) {
  const common = {
    coreRoot,
    editionRoot: coreRoot,
    distributionConfig: 'config/distributions/generic.json',
    version: '0.0.0',
    verifySnapshot: true,
    runtimeSource: '',
    upstreamSource: '',
  }
  const platforms = {
    macos: [...sharedDesktopStages(common), ...macosStages({
      coreRoot, name: 'EduWork', version: '0.0.0', development: true, releaseNotesFile: '', receiptBase: {},
    })],
    windows: [...sharedDesktopStages(common), ...windowsStages({ coreRoot, receiptBase: {} })],
  }
  const stages = sharedDiagramStages(platforms)
  const edges = diagramEdges(platforms)
  await mkdir(output, { recursive: true })
  const written = []
  for (const [platform, stages] of Object.entries(platforms)) {
    await writeFile(join(output, `build-pipeline-${platform}.json`), JSON.stringify(catalog({ platform, stages }), null, 2) + '\n')
    written.push(`build-pipeline-${platform}.json`)
  }
  const title = 'EduWork 双平台桌面构建流程'
  const subtitle = 'Windows x64 与 macOS arm64 共用主流程；蓝色步骤仅在 macOS 执行'
  await writeFile(join(output, 'build-pipeline.drawio'), drawioXml({ title, stages, edges }))
  await writeFile(join(output, 'build-pipeline.mmd'), mermaidDiagram({ stages, edges }))
  await writeFile(join(output, 'build-pipeline.svg'), svgDiagram({ title, subtitle, stages, edges }))
  written.push('build-pipeline.drawio', 'build-pipeline.mmd', 'build-pipeline.svg')
  return written
}

if (isMainModule(import.meta.url)) {
  const { values } = parseArgs({ options: { output: { type: 'string' } } })
  const output = values.output ?? join(coreRoot, 'docs/assets')
  const written = await buildPipelineDiagrams({ output })
  console.log(`Wrote ${written.length} files to ${output}`)
  for (const file of written) console.log(`  ${file}`)
}
