// Generate the build-pipeline diagrams from the stage declarations.
//
// These were previously drawn by hand and had already drifted: both said
// "1191 files" when the real count was 1261, and their stage numbering existed
// nowhere in the repository. Everything here is derived from the same stage
// catalogs the build runs, so a picture cannot disagree with the pipeline.
//
// Four outputs per platform:
//   .drawio — the editable source of record
//   .svg    — the rendered view; diffable and checked in, so it cannot go stale
//   .mmd    — a text form for readers and for tools that consume Mermaid
//   .json   — the machine-readable catalog for tooling
//
// The .svg is generated by this file rather than exported by hand from the
// .drawio. A hand-exported raster cannot be compared in a test, which is how the
// previous diagrams drifted in the first place.
import { createHash } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'
import { isMainModule } from './lib/build-util.mjs'
import { parallelSets } from './lib/stage-runner.mjs'
import { sharedDesktopStages } from './lib/shared-desktop-stages.mjs'
import { macosStages } from './lib/macos-stages.mjs'
import { windowsStages } from './lib/windows-stages.mjs'

const scriptRoot = dirname(fileURLToPath(import.meta.url))
const coreRoot = join(scriptRoot, '..')

const xml = value => String(value)
  .replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')
  .replaceAll('"', '&quot;')

// ---------------------------------------------------------------- drawio ----

/** Geometry: a fixed grid, one column per wave, one row per stage in the wave. */
const COLUMN_WIDTH = 260
const ROW_HEIGHT = 90
const BOX_WIDTH = 200
const BOX_HEIGHT = 60
const MARGIN = 40

function layout(stages) {
  const waves = parallelSets(stages)
  const placed = new Map()
  waves.forEach((wave, column) => {
    wave.forEach((name, row) => {
      placed.set(name, {
        x: MARGIN + column * COLUMN_WIDTH,
        y: MARGIN + row * ROW_HEIGHT,
        column,
        row,
      })
    })
  })
  const height = MARGIN * 2 + Math.max(...waves.map(wave => wave.length)) * ROW_HEIGHT
  const width = MARGIN * 2 + waves.length * COLUMN_WIDTH
  return { placed, waves, width, height }
}

function drawioXml({ title, stages, platform }) {
  const { placed, waves, width, height } = layout(stages)
  const cells = []
  let id = 0
  const nextId = () => `n${id += 1}`

  // One label per wave, so the parallel sets are visible rather than implied.
  waves.forEach((wave, column) => {
    cells.push(`        <mxCell id="${nextId()}" value="${xml(`wave ${column} — ${wave.length} stage(s)`)}" style="text;html=1;align=center;verticalAlign=middle;fontSize=11;fontColor=#57606a;" vertex="1" parent="1">
          <mxGeometry x="${MARGIN + column * COLUMN_WIDTH}" y="${MARGIN - 26}" width="${BOX_WIDTH}" height="20" as="geometry"/>
        </mxCell>`)
  })

  const ids = new Map()
  for (const entry of stages) {
    const spot = placed.get(entry.name)
    const cellId = nextId()
    ids.set(entry.name, cellId)
    const dependencies = [...entry.requires, ...entry.dependsOn]
    const kind = entry.mutableOutputs.length ? 'mutable output' : 'outputs'
    const label = [
      entry.name,
      entry.description ? `— ${entry.description}` : '',
      `${dependencies.length} in · ${entry.outputs.length + entry.mutableOutputs.length} ${kind}`,
    ].filter(Boolean).join('\n')
    cells.push(`        <mxCell id="${cellId}" value="${xml(label)}" style="rounded=1;whiteSpace=wrap;html=1;fillColor=${entry.mutableOutputs.length ? '#fff8e5' : '#ffffff'};strokeColor=${entry.mutableOutputs.length ? '#d4a72c' : '#d0d7de'};fontSize=11;" vertex="1" parent="1">
          <mxGeometry x="${spot.x}" y="${spot.y}" width="${BOX_WIDTH}" height="${BOX_HEIGHT}" as="geometry"/>
        </mxCell>`)
  }

  const edges = []
  for (const entry of stages) {
    for (const dependency of [...entry.requires, ...entry.dependsOn]) {
      // Hashed dependencies are solid; ordering-only edges are dashed, because
      // the distinction decides whether a change invalidates the stage.
      const hashed = entry.requires.includes(dependency)
      edges.push(`        <mxCell id="${nextId()}" style="edgeStyle=orthogonalEdgeStyle;rounded=0;html=1;${hashed ? '' : 'dashed=1;'}strokeColor=${hashed ? '#1f883d' : '#afb8c1'};endArrow=block;exitX=1;exitY=0.5;entryX=0;entryY=0.5;" edge="1" parent="1" source="${ids.get(dependency)}" target="${ids.get(entry.name)}">
          <mxGeometry relative="1" as="geometry"/>
        </mxCell>`)
    }
  }

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/build-pipeline-diagram.mjs — do not edit by hand. -->
<mxfile host="EduWork" version="24.0.0">
  <diagram id="build-pipeline-${platform}" name="${xml(title)}">
    <mxGraphModel dx="1200" dy="800" grid="1" gridSize="10" guides="1" tooltips="1" connect="1" arrows="1" fold="1" page="1" pageScale="1" pageWidth="${width + MARGIN * 2}" pageHeight="${height + MARGIN * 2}" math="0" shadow="0">
      <root>
        <mxCell id="0"/>
        <mxCell id="1" parent="0"/>
${cells.join('\n')}
${edges.join('\n')}
      </root>
    </mxGraphModel>
  </diagram>
</mxfile>
`
}

// ------------------------------------------------------------------- svg ----

const CARD_W = 210
const CARD_H = 104
const COL_GAP = 92
const ROW_GAP = 30
const PAD_X = 48
const PAD_TOP = 118
const PAD_BOTTOM = 64
const DESC_LIMIT = 26

// GitHub's own palette, so the diagram reads as part of the product's docs
// rather than as a separate drawing.
const C = {
  bg: '#ffffff',
  border: '#d0d7de',
  ink: '#1f2328',
  muted: '#59636e',
  faint: '#8c959f',
  card: '#ffffff',
  cardEdge: '#d0d7de',
  cardMutable: '#fff8e5',
  cardMutableEdge: '#d4a72c',
  solid: '#1f883d',
  dashed: '#afb8c1',
  lane: '#f6f8fa',
}

/** Longest-path depth per stage: a stage sits as early as its dependencies allow. */
function wavesOf(stages) {
  const depth = new Map()
  const visiting = new Set()
  const deps = entry => [...entry.requires, ...entry.dependsOn]
  const depthOf = name => {
    if (depth.has(name)) return depth.get(name)
    if (visiting.has(name)) return 0
    const entry = stages.find(candidate => candidate.name === name)
    if (!entry) return 0
    visiting.add(name)
    const dependencies = deps(entry)
    const value = dependencies.length ? Math.max(...dependencies.map(depthOf)) + 1 : 0
    visiting.delete(name)
    depth.set(name, value)
    return value
  }
  for (const entry of stages) depthOf(entry.name)
  const byLevel = new Map()
  for (const entry of stages) {
    const level = depth.get(entry.name)
    if (!byLevel.has(level)) byLevel.set(level, [])
    byLevel.get(level).push(entry.name)
  }
  return [...byLevel.keys()].sort((a, b) => a - b).map(level => byLevel.get(level))
}

function svgDiagram({ title, subtitle, stages }) {
  const waves = wavesOf(stages)
  const spot = new Map()
  waves.forEach((wave, col) => wave.forEach((name, row) => spot.set(name, { col, row })))
  const rows = Math.max(...waves.map(wave => wave.length))
  const width = PAD_X * 2 + waves.length * CARD_W + (waves.length - 1) * COL_GAP
  const height = PAD_TOP + rows * CARD_H + (rows - 1) * ROW_GAP + PAD_BOTTOM
  const pos = name => {
    const { col, row } = spot.get(name)
    return { x: PAD_X + col * (CARD_W + COL_GAP), y: PAD_TOP + row * (CARD_H + ROW_GAP) }
  }
  const font = '-apple-system,BlinkMacSystemFont,"Segoe UI",Helvetica,Arial,sans-serif'
  const mono = 'ui-monospace,SFMono-Regular,Menlo,monospace'

  const parts = []
  parts.push(`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-label="${xml(title)}">`)
  parts.push(`<style>
  .t{font:600 14px ${font};fill:${C.ink}}
  .s{font:400 11.5px ${font};fill:${C.muted}}
  .h{font:600 17px ${font};fill:${C.ink}}
  .m{font:400 11.5px ${font};fill:${C.faint}}
  .n{font:600 11px ${mono};fill:${C.faint}}
  .p{font:400 10.5px ${mono};fill:${C.faint}}
</style>`)
  parts.push(`<rect width="${width}" height="${height}" fill="${C.bg}"/>`)
  // Header strip: the pipeline identity and a summary line, the way a workflow
  // run page presents a run.
  parts.push(`<rect x="${PAD_X - 17}" y="18" width="${width - (PAD_X - 17) * 2}" height="58" rx="8" fill="${C.bg}" stroke="${C.border}"/>`)
  parts.push(`<circle cx="${PAD_X - 1}" cy="41" r="5" fill="${C.solid}"/>`)
  parts.push(`<text class="h" x="${PAD_X + 14}" y="46">${xml(title)}</text>`)
  parts.push(`<text class="s" x="${PAD_X - 1}" y="65">${xml(subtitle)}</text>`)

  // One lane per wave, labelled, so "what can run together" is a column.
  waves.forEach((wave, col) => {
    const x = PAD_X + col * (CARD_W + COL_GAP)
    parts.push(`<rect x="${x - 12}" y="${PAD_TOP - 22}" width="${CARD_W + 24}" height="${rows * CARD_H + (rows - 1) * ROW_GAP + 36}" rx="10" fill="${C.lane}"/>`)
    parts.push(`<text class="n" x="${x}" y="${PAD_TOP - 32}">wave ${col}</text>`)
    parts.push(`<text class="m" x="${x + CARD_W}" y="${PAD_TOP - 32}" text-anchor="end">${wave.length} stage${wave.length === 1 ? '' : 's'}</text>`)
  })

  // Edges first, so the cards sit on top of them.
  for (const entry of stages) {
    const to = pos(entry.name)
    for (const dependency of [...entry.requires, ...entry.dependsOn]) {
      const from = pos(dependency)
      const hashed = entry.requires.includes(dependency)
      const x1 = from.x + CARD_W, y1 = from.y + CARD_H / 2
      const x2 = to.x, y2 = to.y + CARD_H / 2
      const mid = (x1 + x2) / 2
      parts.push(`<path d="M${x1} ${y1} H${mid} V${y2} H${x2}" fill="none" stroke="${hashed ? C.solid : C.dashed}" stroke-width="${hashed ? 1.6 : 1.3}"${hashed ? '' : ' stroke-dasharray="4 3"'} marker-end="url(#${hashed ? 'ah' : 'ahd'})"/>`)
    }
  }
  parts.push(`<defs>
  <marker id="ah" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto"><path d="M0 0 L10 5 L0 10 z" fill="${C.solid}"/></marker>
  <marker id="ahd" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto"><path d="M0 0 L10 5 L0 10 z" fill="${C.dashed}"/></marker>
</defs>`)

  for (const entry of stages) {
    const p = pos(entry.name)
    const mutable = entry.mutableOutputs.length > 0
    parts.push(`<g><rect x="${p.x}" y="${p.y}" width="${CARD_W}" height="${CARD_H}" rx="8" fill="${mutable ? C.cardMutable : C.card}" stroke="${mutable ? C.cardMutableEdge : C.cardEdge}" stroke-width="1"/>`)
    parts.push(`<text class="t" x="${p.x + 15}" y="${p.y + 28}">${xml(entry.name)}</text>`)
    const description = entry.description ?? ''
    if (description) {
      // The card is a fixed width, so a long description is clipped rather than
      // allowed to spill over the edge.
      const short = description.length > DESC_LIMIT ? `${description.slice(0, DESC_LIMIT - 1)}…` : description
      parts.push(`<text class="s" x="${p.x + 15}" y="${p.y + 48}">${xml(short)}</text>`)
    }
    const dependencies = entry.requires.length + entry.dependsOn.length
    const outputs = entry.outputs.length + entry.mutableOutputs.length
    parts.push(`<text class="p" x="${p.x + 15}" y="${p.y + 72}">in ${dependencies} · out ${outputs}${mutable ? ' · mutable' : ''}</text>`)
    const names = [...new Set([...entry.outputs, ...entry.mutableOutputs].map(output => output.split('/')[0]))].slice(0, 2)
    if (names.length) parts.push(`<text class="p" x="${p.x + 15}" y="${p.y + 89}">${xml(names.join(', '))}</text>`)
    parts.push(`</g>`)
  }

  const legendY = height - 22
  parts.push(`<path d="M${PAD_X} ${legendY} H${PAD_X + 26}" stroke="${C.solid}" stroke-width="1.6" marker-end="url(#ah)"/>`)
  parts.push(`<text class="m" x="${PAD_X + 34}" y="${legendY + 4}">hashed dependency (changes invalidate)</text>`)
  parts.push(`<path d="M${PAD_X + 250} ${legendY} H${PAD_X + 276}" stroke="${C.dashed}" stroke-width="1.3" stroke-dasharray="4 3" marker-end="url(#ahd)"/>`)
  parts.push(`<text class="m" x="${PAD_X + 284}" y="${legendY + 4}">ordering only</text>`)
  parts.push(`<rect x="${PAD_X + 400}" y="${legendY - 7}" width="14" height="14" rx="3" fill="${C.cardMutable}" stroke="${C.cardMutableEdge}"/>`)
  parts.push(`<text class="m" x="${PAD_X + 420}" y="${legendY + 4}">mutable output</text>`)
  parts.push(`</svg>`)
  return `${parts.join('\n')}\n`
}

// --------------------------------------------------------------- mermaid ----

function mermaidDiagram({ stages, platform }) {
  const lines = [
    '%% Generated by scripts/build-pipeline-diagram.mjs — do not edit by hand.',
    'flowchart LR',
  ]
  for (const entry of stages) {
    const shape = entry.mutableOutputs.length ? `["${entry.name}<br/>mutable"]` : `["${entry.name}"]`
    lines.push(`  ${entry.name.replaceAll('-', '_')}${shape}`)
  }
  for (const entry of stages) {
    for (const dependency of entry.requires) {
      lines.push(`  ${dependency.replaceAll('-', '_')} --> ${entry.name.replaceAll('-', '_')}`)
    }
    for (const dependency of entry.dependsOn) {
      lines.push(`  ${dependency.replaceAll('-', '_')} -.-> ${entry.name.replaceAll('-', '_')}`)
    }
  }
  lines.push(`  classDef mutable fill:${C.cardMutable},stroke:${C.cardMutableEdge}`)
  lines.push('  subgraph legend[" "]')
  lines.push('    direction LR')
  lines.push(`    l1["hashed dependency"]:::legendSolid --> l2[" "]:::legendBlank`)
  lines.push('  end')
  lines.push(`  classDef legendSolid fill:${C.bg},stroke:${C.solid}`)
  lines.push(`  classDef legendBlank fill:none,stroke:none`)
  return `${lines.join('\n')}\n`
}

// --------------------------------------------------------------- catalog ----

function catalog({ platform, stages }) {
  const waves = parallelSets(stages)
  return {
    platform,
    generatedFrom: 'stage declarations in scripts/lib/*-stages.mjs',
    stages: stages.length,
    maxParallelism: Math.max(...waves.map(wave => wave.length)),
    waves: waves.map((wave, index) => ({ wave: index, stages: wave })),
    detail: stages.map(entry => ({
      name: entry.name,
      description: entry.description,
      requires: entry.requires,
      dependsOn: entry.dependsOn,
      outputs: entry.outputs,
      mutableOutputs: entry.mutableOutputs,
      clean: entry.clean,
    })),
  }
}

/** A stable digest of the rendered assets, for a caller that wants to pin them. */
export function assetsDigest(assets) {
  return createHash('sha256').update(JSON.stringify(assets)).digest('hex')
}

export async function buildPipelineDiagrams({ output }) {
  const common = {
    coreRoot,
    editionRoot: coreRoot,
    distributionConfig: 'config/distributions/generic.json',
    version: '0.0.0',
    verifySnapshot: true,
    runtimeSource: '',
    upstreamSource: '',
  }
  const platforms = {
    macos: [...sharedDesktopStages(common), ...macosStages({
      coreRoot, name: 'EduWork', version: '0.0.0', development: true, releaseNotesFile: '', receiptBase: {},
    })],
    windows: [...sharedDesktopStages(common), ...windowsStages({ coreRoot, receiptBase: {} })],
  }
  await mkdir(output, { recursive: true })
  const written = []
  for (const [platform, stages] of Object.entries(platforms)) {
    const title = `${platform === 'macos' ? 'macOS arm64' : 'Windows x64'} desktop build pipeline`
    const waves = parallelSets(stages)
    const subtitle = `${stages.length} stages · ${waves.length} waves · max ${Math.max(...waves.map(wave => wave.length))} parallel · generated from the stage declarations`
    await writeFile(join(output, `build-pipeline-${platform}.drawio`), drawioXml({ title, stages, platform }))
    await writeFile(join(output, `build-pipeline-${platform}.svg`), svgDiagram({ title, subtitle, stages }))
    await writeFile(join(output, `build-pipeline-${platform}.mmd`), mermaidDiagram({ stages, platform }))
    await writeFile(join(output, `build-pipeline-${platform}.json`), JSON.stringify(catalog({ platform, stages }), null, 2) + '\n')
    written.push(
      `build-pipeline-${platform}.drawio`,
      `build-pipeline-${platform}.svg`,
      `build-pipeline-${platform}.mmd`,
      `build-pipeline-${platform}.json`,
    )
  }
  return written
}

if (isMainModule(import.meta.url)) {
  const { values } = parseArgs({ options: { output: { type: 'string' } } })
  const output = values.output ?? join(coreRoot, 'docs/assets')
  const written = await buildPipelineDiagrams({ output })
  console.log(`Wrote ${written.length} files to ${output}`)
  for (const file of written) console.log(`  ${file}`)
}
