import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { join, resolve } from 'node:path'
import { pathToFileURL, fileURLToPath } from 'node:url'
import { randomUUID } from 'node:crypto'
import { parseArgs } from 'node:util'

// Uses an assembled rc.1 product and real Host with an isolated synthetic home.
// No model requests or user credentials are needed. Output must be a new directory.
const { values } = parseArgs({ options: {
 product: { type: 'string' }, host: { type: 'string' }, output: { type: 'string' },
 browser: { type: 'string', default: 'msedge' },
} })
if (!values.product || !values.host || !values.output) throw Error('Use --product <assembled rc.1 product> --host <native Host> --output <new directory> [--browser msedge]')
const repo=fileURLToPath(new URL('../../../',import.meta.url))
const product=resolve(values.product), hostRoot=resolve(values.host), output=resolve(values.output)
const { prepareProductProfile }=await import(pathToFileURL(join(repo,'dsh-host/product-profile.mjs')))
const { startNativeBridge }=await import(pathToFileURL(join(repo,'dsh-electron/src/native-vault.mjs')))
const { DesktopHostProcess }=await import(pathToFileURL(join(hostRoot,'host-process.mjs')))
const { chromium }=createRequire(join(product,'d/package.json'))('playwright-core')
await mkdir(output)
const config=join(output,'eduwork.jsonc')
await writeFile(config,JSON.stringify({schemaVersion:1,product:{name:'EduWork'}}))
const secrets=new Map()
const vault={async flush(){},async operation(op,ref,value){if(op==='set')secrets.set(ref,value);if(op==='unset')secrets.delete(ref);return {configured:secrets.has(ref),writable:true,source:'synthetic',...(op==='resolve'&&secrets.has(ref)?{value:secrets.get(ref)}:{})}}}
const bridge=await startNativeBridge({vault,attention(){},openExternal(){throw Error('Unexpected navigation')}})
let host,browser,page
const report={success:false,checks:[],pageErrors:[]},logs=[]
try{
 const prepared=await prepareProductProfile({product,home:join(output,'home'),shell:'electron',userConfig:config})
 host=new DesktopHostProcess(process.execPath,join(product,'d'),prepared.profile,undefined,{...process.env,...prepared.environment},undefined,undefined,undefined,undefined,{bootstrap:bridge.bootstrap,onLog:line=>logs.push(line)})
 const ready=await host.start()
 const {authenticateWebHost}=await import(pathToFileURL(join(hostRoot,'web-document.mjs')))
 const origin=new URL(ready.url).origin, cookie=await authenticateWebHost(ready.url)
 const rpc=async(method,args={})=>{
  const response=await fetch(origin+'/api/'+method,{method:'POST',headers:{cookie,origin,'content-type':'application/json'},body:JSON.stringify({type:'client-request',rpcId:randomUUID(),method,payload:{args}})})
  const result=await response.json();assert.equal(result.result?.ok,true,JSON.stringify(result));return result.result.value
 }
 browser=await chromium.launch({channel:values.browser,headless:true})
 page=await browser.newPage({viewport:{width:1280,height:850}})
 page.on('pageerror',e=>report.pageErrors.push(e.message))
 await page.goto(ready.url)
 await page.getByRole('button',{name:'稍后配置',exact:true}).click({timeout:30000})
 await page.getByRole('button',{name:'插件',exact:true}).click()
 await page.locator('[data-plugin-item]').first().waitFor()
 assert.equal(await page.locator('[data-plugin-item="eduwork-skills"]').count(),0)
 assert.equal(await page.getByRole('searchbox',{name:'搜索技能'}).count(),0)
 await page.screenshot({path:join(output,'plugins.png')})
 const skillsEntry=page.getByRole('button',{name:'技能',exact:true}),pluginsEntry=page.getByRole('button',{name:'插件',exact:true})
 assert.equal(await skillsEntry.count(),1)
 assert.equal(await skillsEntry.evaluate((el)=>el.parentElement===document.querySelector('button[aria-label="插件"]').parentElement),true)
 await skillsEntry.press('Enter')
 await page.getByRole('searchbox',{name:'搜索技能'}).waitFor()
 assert.equal(await page.getByRole('heading',{name:'技能',exact:true}).count(),1)
 assert.equal(await skillsEntry.getAttribute('aria-current'),'page')
 assert.equal(await pluginsEntry.getAttribute('aria-current'),null)
 report.checks.push('Skills and Plugins are sidebar peers; keyboard selection; no Skills plugin item; one page heading')
 const word=page.locator('[data-skill-name="artifact-documents"]').getByRole('switch')
 await word.waitFor()
 await page.screenshot({path:join(output,'skills.png')})
 await page.setViewportSize({width:1000,height:760})
 await page.waitForFunction(()=>document.querySelector('button[aria-label="技能"]')?.textContent.trim()==='')
 await page.screenshot({path:join(output,'skills-1000.png')})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false)
 const lastCard=page.locator('[data-skill-name]').last()
 await lastCard.scrollIntoViewIfNeeded()
 assert.equal(await lastCard.isVisible(),true)
 await page.getByRole('heading',{name:'技能',exact:true}).scrollIntoViewIfNeeded()
 await page.setViewportSize({width:1280,height:850})
 await page.getByRole('button',{name:/收起侧边栏/}).click()
 await page.waitForFunction(()=>document.querySelector('button[aria-label="技能"]')?.textContent.trim()==='')
 await pluginsEntry.click()
 await skillsEntry.press('Enter')
 await word.waitFor()
 assert.equal(await skillsEntry.getAttribute('aria-current'),'page')
 await page.screenshot({path:join(output,'skills-collapsed.png')})
 await page.getByRole('button',{name:/打开侧边栏/}).click()
 report.checks.push('Collapsed sidebar remains accessible; switching between panels; page scroll and 1000px viewport')
 assert.equal(await word.isChecked(),true)
 await word.click()
 await page.waitForFunction(()=>document.querySelector('[data-skill-name="artifact-documents"] [role="switch"]')?.getAttribute('aria-checked')==='false')
 await page.getByRole('searchbox',{name:'搜索技能'}).fill('Word')
 assert.equal(await page.locator('[data-skill-name]').count(),1)
 await page.reload()
 await page.getByRole('button',{name:'稍后配置',exact:true}).click({timeout:30000})
 await skillsEntry.click()
 await word.waitFor()
 assert.equal(await word.isChecked(),false)
 report.checks.push('Search and toggle persistence after client reload')
 await page.getByRole('button',{name:'创建技能',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'创建个人技能'})
 await dialog.getByLabel('技能标识',{exact:true}).fill('synthetic-entry-check')
 await dialog.getByLabel('用途说明',{exact:true}).fill('Synthetic entry migration test')
 await dialog.getByLabel('工作指令',{exact:true}).fill('Only used by a local UI test. Do not call external services.')
 await dialog.getByRole('button',{name:'创建',exact:true}).click()
 const custom=page.locator('[data-skill-name="synthetic-entry-check"]')
 await custom.waitFor()
 await custom.getByRole('button',{name:'移除',exact:true}).click()
 await page.getByRole('dialog',{name:'移除个人技能'}).getByRole('button',{name:'移除',exact:true}).click()
 await custom.waitFor({state:'detached'})
 report.checks.push('Personal skill creation and removal through original service')
 const workspace=join(output,'Synthetic project'),skill=join(workspace,'.agents/skills/sidebar-project-check')
 await mkdir(skill,{recursive:true})
 await mkdir(join(workspace,'.git'))
 await writeFile(join(skill,'SKILL.md'),'---\nname: sidebar-project-check\ndescription: Synthetic project skill to verify navigation context.\n---\nOnly use for this local test.\n')
 await rpc('workspace/create',{request:{path:workspace}})
 const projectRow=page.locator('[data-row-key]').filter({hasText:'Synthetic project'})
 await projectRow.hover()
 await projectRow.getByRole('button',{name:/新.*会话/}).click()
 await page.waitForFunction(()=>document.querySelector('button[aria-label="技能"]')?.getAttribute('aria-current')!=='page')
 await skillsEntry.click()
 await page.locator('[data-skill-name="sidebar-project-check"]').waitFor()
 await pluginsEntry.click()
 await skillsEntry.click()
 await page.locator('[data-skill-name="sidebar-project-check"]').waitFor()
 assert.equal(await page.getByText('打开一个项目后，还会显示该项目专属的技能。',{exact:true}).count(),0)
 report.checks.push('Current session and its project skill survive navigation between conversation, Skills and Plugins')
 await pluginsEntry.click()
 await page.getByRole('button',{name:'设置',exact:true}).click()
 await page.getByText('内置插件',{exact:true}).last().click()
 assert.equal(await page.getByRole('searchbox',{name:'搜索技能'}).count(),0)
 report.checks.push('No duplicate Skills entry in Settings')
 assert.deepEqual(report.pageErrors,[])
 report.success=true
}catch(error){report.error=error.stack;await page?.screenshot({path:join(output,'failure.png')});throw error}
finally{await browser?.close();await host?.stop();await bridge.close();await writeFile(join(output,'report.json'),JSON.stringify(report,null,2));await writeFile(join(output,'host.log'),logs.join(''))}
console.log(JSON.stringify(report,null,2))

