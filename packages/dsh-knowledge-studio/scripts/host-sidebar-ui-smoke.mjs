import assert from 'node:assert/strict'
import {mkdir,writeFile,readFile} from 'node:fs/promises'
import {join,resolve} from 'node:path'
import {chromium,expect} from '@playwright/test'
import {startIsolatedHost} from './host-process.mjs'

const directory=resolve(process.env.STUDIO_HOST_UI_OUTPUT||'dist/host-sidebar-ui')
const hostVersion=JSON.parse(await readFile(resolve(process.env.STUDIO_TEST_DSH_RUNTIME||'.','node_modules/@deepseek-ai/dsh/package.json'),'utf8')).version
await mkdir(directory,{recursive:true})
const host=await startIsolatedHost({syntheticMindmap:true,globalPanelFixture:hostVersion==='0.1.5-rc.1'})
let browser,page
try {
  browser=await chromium.launch({headless:true,...(process.env.STUDIO_TEST_BROWSER?{executablePath:process.env.STUDIO_TEST_BROWSER}:{})})
  page=await browser.newPage({locale:'zh-CN',viewport:{width:1440,height:900}})
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  const preferenceRequests=[]
  page.on('request',request=>{if(/knowledgeStudio\/(readUIPreferences|setUIOpenPreference)/.test(request.url()))preferenceRequests.push(request.url().split('/').at(-1))})
  await page.goto(host.launch)
  const base=new URL(host.launch).origin
  const rpc=async(method,args)=>{
    const response=await page.request.post(base+'/api/'+method,{headers:{origin:base},data:{type:'client-request',rpcId:'sidebar-smoke',method,payload:{args}}})
    const result=(await response.json()).result;assert.equal(result.ok,true,JSON.stringify(result));return result.value
  }
  const renamed=await rpc('session/rename',{request:{sessionId:host.fixture.sessionId,title:host.fixture.title}})
  await rpc('knowledgeStudio/setUIOpenPreference',{open:true})
  await page.reload()
  await page.getByRole('button',{name:'继续',exact:true}).click()
  await page.getByRole('button',{name:'稍后配置',exact:true}).click()
  if(!await page.getByText(renamed.title,{exact:true}).count())await page.getByText('合成工作区',{exact:true}).first().click()
  await page.getByText(renamed.title,{exact:true}).first().click()
  const entry=page.getByRole('button',{name:'Studio 从工作区资料创建成果',exact:true})
  const expand=page.locator('[data-sidebar-right-expand]')
  const collapse=page.locator('[data-sidebar-right-toggle]')
  const startTab=page.getByRole('tab').filter({has:page.locator('[data-dockkit-tab-title]',{hasText:/^开始$/})})
  const openStart=async()=>{
    if(await startTab.count())await startTab.click()
    else await page.getByRole('button',{name:'新标签页',exact:true}).click()
    await expect(entry).toBeVisible()
  }
  const studio=page.locator('[data-knowledge-studio-details],svg[data-mindmap-canvas]')
  const studioTab=page.getByRole('tab').filter({has:page.locator('[data-dockkit-tab-title]',{hasText:/^Studio$/})})
  const draft=page.locator('[data-composer-input="true"]')
  const reading=page.locator('[data-studio-reading-layer]')
  const settledPanel=()=>expect.poll(async()=>{
    const box=await page.locator('[data-sidebar-right-panel]').boundingBox()
    return Boolean(box&&box.width>300&&box.x>=-1&&box.x+box.width<=page.viewportSize().width+1)
  }).toBe(true)
  await expect(page.locator('[data-knowledge-studio-entry]')).toHaveCount(0)
  await expect(studioTab).toHaveCount(0)
  await expand.click()
  await expect(startTab).toHaveCount(1)
  await expect(entry).toBeVisible()
  await draft.fill('官方侧栏保留的未发送草稿')
  await entry.click()
  await expect(studioTab).toHaveCount(1)
  await expect(studio).toBeVisible()
  await expect(page.locator('[data-knowledge-studio-capability]')).toHaveCount(8)
  await settledPanel()
  await page.screenshot({path:join(directory,'official-studio.png')})
  await page.getByText(host.fixture.artifacts[0].title,{exact:true}).last().click()
  await expect(page.locator('[data-mindmap-node]')).toHaveCount(17)
  if(hostVersion==='0.1.5-rc.1'){
    await page.getByRole('button',{name:'全局面板测试',exact:true}).click()
    await expect(page.getByText('全局面板测试内容',{exact:true})).toBeVisible()
    await expect(studio).toHaveCount(0)
    await page.getByText(renamed.title,{exact:true}).first().click()
    await expect(studioTab).toHaveCount(1)
    await expect(page.locator('[data-mindmap-node]')).toHaveCount(17)
    await expect(draft).toHaveText('官方侧栏保留的未发送草稿')
  }
  await expect(reading).toHaveCount(0)
  await expect(page.getByRole('button',{name:/^展开阅读/})).toHaveCount(0)
  await page.locator('[data-sidebar-right-mode="fullscreen"]').click()
  await expect(page.locator('[data-sidebar-right-panel="fullscreen"]')).toBeVisible()
  await expect(page.locator('[data-mindmap-node]')).toHaveCount(17)
  await page.locator('[data-sidebar-right-mode="push"]').click()
  await expect(page.locator('[data-sidebar-right-panel="push"]')).toBeVisible()
  await expect(draft).toHaveText('官方侧栏保留的未发送草稿')
  await collapse.click()
  await expect(expand).toBeVisible()
  await expand.click()
  await expect(studioTab).toHaveCount(1)
  await expect(studio).toBeVisible()
  await openStart()
  await page.getByRole('button',{name:/^(?:工作区文件 浏览会话工作区的文件|文件 浏览这个会话工作区里的文件，点开就能查看。)$/}).click()
  const filesTab=page.getByRole('tab').filter({has:page.locator('[data-dockkit-tab-title]',{hasText:/^(?:工作区文件|文件)$/})})
  await expect(filesTab).toHaveCount(1)
  await page.getByText('readme.md',{exact:true}).click()
  const previewTab=page.getByRole('tab').filter({has:page.locator('[data-dockkit-tab-title]',{hasText:/^readme.md$/})})
  await expect(previewTab).toHaveCount(1)
  await expect(page.getByText(/Synthetic Studio sources/)).toBeVisible()
  await openStart();await entry.click();await expect(studio).toBeVisible()
  await expect(filesTab).toHaveCount(1)
  await expect(previewTab).toHaveCount(1)
  await studioTab.locator('[data-dockkit-tab-close]').click()
  await expect(studioTab).toHaveCount(0)
  await expect(filesTab).toHaveCount(1)
  await openStart();await entry.click();await expect(studio).toBeVisible()
  await page.setViewportSize({width:760,height:900})
  await expect(page.locator('[data-sidebar-right-panel="fullscreen"]')).toBeVisible()
  await expect(studio).toBeVisible()
  await settledPanel()
  await page.screenshot({path:join(directory,'official-narrow.png')})
  await page.setViewportSize({width:1440,height:900})
  await expect(page.locator('[data-sidebar-right-panel="push"]')).toBeVisible()
  await expect(studio).toBeVisible()
  await expect(draft).toHaveText('官方侧栏保留的未发送草稿')
  await expect.poll(()=>rpc('knowledgeStudio/readUIPreferences',{})).toEqual({open:true})
  await page.getByRole('button',{name:'新建会话',exact:true}).first().click()
  await page.getByRole('button',{name:'稍后配置',exact:true}).click()
  await expect(studioTab).toHaveCount(0)
  await expect(page.locator('[data-knowledge-studio-entry]')).toHaveCount(0)
  // Respect the official host's blank-session navigation. Studio does not
  // recreate an entry when the host does not show its sidebar control.
  const blankEntryAvailable=await expand.count()>0
  if(blankEntryAvailable){
    await expand.click()
    await expect(startTab).toHaveCount(1)
    await expect(entry).toBeVisible()
    await entry.click()
    await expect(studioTab).toHaveCount(1)
    await expect(page.locator('[data-sidebar-right-panel] [data-knowledge-studio-details]')).toBeVisible()
    await expect(reading).toHaveCount(0)
    await settledPanel()
  }
  await page.screenshot({path:join(directory,'official-blank-session.png')})
  await page.getByText(renamed.title,{exact:true}).first().click()
  await expect(studioTab).toHaveCount(1)
  await expect(studio).toBeVisible()
  await expect(filesTab).toHaveCount(1)
  await expect(draft).toHaveText('官方侧栏保留的未发送草稿')
  await page.locator('[data-sidebar-right-mode="fullscreen"]').click()
  await page.getByRole('button',{name:'返回 Studio',exact:true}).click()
  await expect(page.locator('[data-knowledge-studio-capability]')).toHaveCount(8)
  await page.getByText(host.fixture.artifacts[0].title,{exact:true}).last().click()
  await page.getByRole('button',{name:'关闭成果',exact:true}).click()
  await expect(studioTab).toHaveCount(0)
  await expect(reading).toHaveCount(0)
  await collapse.click()
  await page.getByRole('button',{name:'新建会话',exact:true}).first().click()
  await page.getByRole('button',{name:'稍后配置',exact:true}).click()
  await expect(page.locator('[data-sidebar-right-panel="fullscreen"]')).toHaveCount(0)
  await expect(reading).toHaveCount(0)
  await expect(draft).toBeEditable()
  await page.getByText(renamed.title,{exact:true}).first().click()
  await expect(studioTab).toHaveCount(0)
  await page.reload()
  await expect(page.locator('[data-knowledge-studio-entry]')).toHaveCount(0)
  await expect(studioTab).toHaveCount(0)
  await expect.poll(()=>rpc('knowledgeStudio/readUIPreferences',{})).toEqual({open:true})
  assert.deepEqual(errors,[])
  assert.deepEqual(preferenceRequests,[],'Native Studio must not read or write legacy open preferences')
  const result={passed:true,scope:'plugin follows official host navigation',blankEntryAvailable,globalMainPanel:hostVersion==='0.1.5-rc.1',dsh:hostVersion,officialSidebar:true,checks:['only native guide entry','eight capabilities','explicit artifact reading','native fullscreen preserves draft without Studio portal','collapse and expand preserve Studio tab','file tab and actual preview survive Studio close','native narrow fullscreen and widening','legacy preference untouched and cannot reopen Studio','new session does not open Studio','session navigation preserves existing tabs and draft'],externalModelCalls:0,errors}
  await writeFile(join(directory,'result.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result))
} catch(error) {
  if(page){await writeFile(join(directory,'failure.txt'),await page.locator('body').innerText());await page.screenshot({path:join(directory,'failure.png')})}
  throw error
} finally {await browser?.close();await host.stop()}
