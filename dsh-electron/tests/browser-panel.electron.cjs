// Native qualification fixture. Run in an isolated Electron harness with
// TEST_SOURCE (repository), TEST_RUNTIME (assembled d/), TEST_OUTPUT (new directory).
const { app, BrowserWindow, WebContentsView, ipcMain } = require('electron')
const { createRequire } = require('node:module')
const { join } = require('node:path')
const { pathToFileURL } = require('node:url')
const fs = require('node:fs')
const assert = require('node:assert/strict')
const { createServer } = require('node:http')
app.setPath('userData', join(process.env.TEST_OUTPUT, 'profile'))
app.on('window-all-closed', () => {})
app.whenReady().then(async () => {
  const root = process.env.TEST_SOURCE, output = process.env.TEST_OUTPUT
  const dependency = createRequire(join(process.env.TEST_RUNTIME, 'package.json'))
  const { BrowserPanel } = await import(pathToFileURL(join(root, 'dsh-electron/src/browser-panel.mjs')))
  const { startBrowserServer } = await import(pathToFileURL(join(root, 'dsh-electron/src/browser-server.mjs')))
  const checks = []
  const window = new BrowserWindow({ show: false, width: 1100, height: 700, webPreferences: { sandbox: true, nodeIntegration: false, contextIsolation: true } })
  const panel = new BrowserPanel({ BrowserWindow, WebContentsView, ipcMain, getWindow: () => window })
  const fixture = createServer((request, response) => {
    const media = { '/sample.pdf': ['application/pdf', 'synthetic-report.pdf'], '/sample.mp4': ['video/mp4', 'video.mp4'] }[request.url]
    if (media && process.env.TEST_MEDIA) { response.setHeader('Content-Type', media[0]); response.end(fs.readFileSync(join(process.env.TEST_MEDIA, media[1]))); return }
    response.end('<!doctype html><title>Browser fixture</title><label for="name">Name</label><input id="name"><p>Fixture body</p>')
  })
  await new Promise(resolve => fixture.listen(0, '127.0.0.1', resolve))
  const url = 'http://127.0.0.1:' + fixture.address().port
  const server = await startBrowserServer({ BrowserWindow, panel, WebSocketServer: dependency('ws').WebSocketServer, version: process.versions.chrome })
  const plugin = join(output, 'tool-browser')
  fs.cpSync(join(root, 'dsh-plugins/tool-browser'), plugin, { recursive: true })
  fs.symlinkSync(join(process.env.TEST_RUNTIME, 'node_modules'), join(plugin, 'node_modules'), 'dir')
  const { apply } = await import(pathToFileURL(join(plugin, 'lib/index.js')))
  const events = new Map()
  let tool, dispose
  process.env.EDUWORK_EXPERIMENTAL_ELECTRON_BROWSER = '1'
  apply({ tools: { register: value => { tool = value } }, get: () => ({ browserConnection: async () => server.connection }),
    on: (name, fn) => events.set(name, fn), effect: fn => { dispose = fn() }, permissionPresets: { current: () => 'workspace-write' } })
  const exec = owner => ({ agent: { session: { id: owner, header: { cwd: output } } } })
  try {
    assert.equal((await events.get('tools/pre-execute')({ ...exec('a'), name: 'browser', args: { action: 'visible' } }, () => ({ kind: 'allow' }))).kind, 'ask')
    assert.equal((await events.get('tools/pre-execute')({ ...exec('a'), name: 'browser', args: { action: 'navigate', mode: 'visible', url } }, () => ({ kind: 'allow' }))).kind, 'ask')
    checks.push('existing DSH visible permission gate')
    await tool.execute({ action: 'navigate', url }, exec('a'))
    const first = panel.pages.get('a')
    assert.ok(first)
    assert.equal(panel.attached, null)
    await tool.execute({ action: 'type', selector: '#name', value: 'retained' }, exec('a'))
    await tool.execute({ action: 'visible' }, exec('a'))
    assert.equal(panel.pages.get('a'), first)
    assert.ok(panel.snapshot('a').revision > 0)
    await panel.command({ action: 'select', owner: 'a' })
    await panel.command({ action: 'bounds', owner: 'a', lease: 'a', bounds: { x: 500, y: 50, width: 550, height: 600 } })
    assert.equal(panel.attached, first)
    await panel.command({ action: 'hide', owner: 'a', lease: 'a' })
    await tool.execute({ action: 'visible' }, exec('a'))
    await panel.command({ action: 'bounds', owner: 'a', lease: 'a2', bounds: { x: 500, y: 50, width: 550, height: 600 } })
    assert.equal(await first.webContents.executeJavaScript('document.querySelector("#name").value'), 'retained')
    assert.equal(await first.webContents.executeJavaScript('window.innerWidth'), 550)
    await panel.command({ action: 'bounds', owner: 'a', lease: 'a2', bounds: { x: 500, y: 50, width: 320, height: 600 } })
    assert.equal(await first.webContents.executeJavaScript('window.innerWidth'), 320)
    assert.equal(await first.webContents.executeJavaScript('matchMedia("(max-width: 400px)").matches'), true)
    checks.push('native viewport follows pane resize from 550px to 320px, including CSS media queries')
    checks.push('real browser tool background/visible preserves the same native page and input')
    await tool.execute({ action: 'navigate', url }, exec('b'))
    assert.notEqual(panel.pages.get('b'), first)
    await tool.execute({ action: 'close' }, exec('b'))
    assert.equal(panel.pages.get('a'), first)
    assert.equal(first.isDestroyed(), false)
    checks.push('two tool sessions and closing the other session are isolated')
    await tool.execute({ action: 'close' }, exec('a'))
    await panel.command({ action: 'select', owner: 'manual' })
    await panel.command({ action: 'open', owner: 'manual', url })
    const manual = panel.pages.get('manual')
    await tool.execute({ action: 'type', selector: '#name', value: 'shared' }, exec('manual'))
    assert.equal(panel.pages.get('manual'), manual)
    assert.equal(await manual.webContents.executeJavaScript('document.querySelector("#name").value'), 'shared')
    checks.push('manual panel and DSH tool adopt the same page')
    await panel.command({ action: 'close', owner: 'manual' })
    await new Promise(resolve => setTimeout(resolve, 150))
    assert.equal(manual.isDestroyed(), true)
    assert.equal(panel.pages.has('manual'), false)
    await panel.command({ action: 'close', owner: 'manual' })
    await tool.execute({ action: 'navigate', url }, exec('manual'))
    assert.notEqual(panel.pages.get('manual'), manual)
    checks.push('UI close destroys adopted page; repeated close and tool reopen succeed')
    await events.get('session/disposed')({ id: 'manual' })
    await new Promise(resolve => setTimeout(resolve, 150))
    assert.equal(panel.pages.has('manual'), false)
    checks.push('DSH session disposal releases the page')
    const { attachExternalNavigation } = await import(pathToFileURL(join(root, 'dsh-electron/src/external-navigation.mjs')))
    await panel.command({ action: 'select', owner: 'links' })
    await window.loadURL('data:text/html,<a id="link" target="_blank">link</a>')
    const errors = []
    attachExternalNavigation(window.webContents, target => panel.openLink(target), error => errors.push(error.message))
    await window.webContents.executeJavaScript(`document.querySelector('a').href=${JSON.stringify(url)};document.querySelector('a').click()`)
    for (let n = 0; n < 100 && !panel.snapshot('links')?.revision; n++) await new Promise(resolve => setTimeout(resolve, 50))
    assert.ok(panel.snapshot('links').revision > 0)
    assert.deepEqual(errors, [])
    checks.push('actual target=_blank link opens a right-panel page without external browser')
    if (process.env.TEST_MEDIA) {
      await panel.openLink(url + '/sample.pdf')
      const page = panel.pages.get('links').webContents
      await new Promise(resolve => setTimeout(resolve, 500))
      const viewerFrame = page.mainFrame.framesInSubtree.find(frame => frame.url.startsWith('chrome-extension://'))
      assert.ok(viewerFrame)
      const pdf = await viewerFrame.executeJavaScript(`(() => { const viewer = document.querySelector('pdf-viewer'); return {loaded:viewer?.loadProgress_, pages:viewer?.docLength_} })()`)
      fs.writeFileSync(join(output, 'pdf-viewer.json'), JSON.stringify(pdf))
      assert.equal(pdf.loaded, 100)
      checks.push('online PDF renders one page in the native viewer')
    }
    fs.writeFileSync(join(output, 'result.json'), JSON.stringify({ passed: true, checks }, null, 2))
  } finally {
    await dispose()
    await server.close()
    panel.close()
    await new Promise(resolve => fixture.close(resolve))
    window.destroy()
  }
  app.exit(0)
}).catch(error => {
  fs.writeFileSync(join(process.env.TEST_OUTPUT, 'result.json'), JSON.stringify({ passed: false, error: error.stack }, null, 2))
  console.error(error)
  app.exit(1)
})
setTimeout(() => { console.error('Native browser panel test timed out'); app.exit(2) }, 90000).unref()
